pub fn drawChar(pixels: []u32, stride: usize, char: u8, x: usize, y: usize, color: u32) void {
    if (char < 32 or char > 126) return;
    const glyph = font_8x8[char - 32];
    for (0..8) |row| {
        const bits = glyph[row];
        for (0..8) |col| {
            if ((bits >> @intCast(7 - col)) & 1 == 1) {
                // Upscale 8x8 into 8x16 by doubling vertical rows
                const px = x + col;
                const py1 = y + row * 2;
                const py2 = py1 + 1;
                if (px < stride) {
                    if (py1 * stride + px < pixels.len) pixels[py1 * stride + px] = color;
                    if (py2 * stride + px < pixels.len) pixels[py2 * stride + px] = color;
                }
            }
        }
    }
}

pub fn drawText(pixels: []u32, stride: usize, text: []const u8, x: usize, y: usize, color: u32) void {
    var cur_x = x;
    for (text) |ch| {
        drawChar(pixels, stride, ch, cur_x, y, color);
        cur_x += font_width;
    }
}

pub fn fillRect(pixels: []u32, stride: usize, x: usize, y: usize, w: usize, h: usize, color: u32) void {
    for (0..h) |dy| {
        const py = y + dy;
        const row_start = py * stride;
        for (0..w) |dx| {
            const px = x + dx;
            if (row_start + px < pixels.len) {
                pixels[row_start + px] = color;
            }
        }
    }
}

pub fn strokeRect(pixels: []u32, stride: usize, x: usize, y: usize, w: usize, h: usize, color: u32) void {
    if (w == 0 or h == 0) return;
    fillRect(pixels, stride, x, y, w, 1, color);
    fillRect(pixels, stride, x, y + h - 1, w, 1, color);
    fillRect(pixels, stride, x, y, 1, h, color);
    fillRect(pixels, stride, x + w - 1, y, 1, h, color);
}

pub fn drawButton(
    pixels: []u32,
    stride: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    text: []const u8,
    is_hover: bool,
    is_active: bool,
    accent_color: u32,
) void {
    const bg_color: u32 = if (is_active) 0x002c3038 else if (is_hover) 0x00262a32 else 0x001c1f25;
    const border_color: u32 = if (is_active) accent_color else if (is_hover) 0x005c6068 else 0x002c3038;
    const text_color: u32 = if (is_active) accent_color else 0x00e6e8ec;

    fillRect(pixels, stride, x, y, w, h, bg_color);
    strokeRect(pixels, stride, x, y, w, h, border_color);

    const text_w = text.len * font_width;
    const text_x = if (w > text_w) x + (w - text_w) / 2 else x + 4;
    const text_y = if (h > font_height) y + (h - font_height) / 2 else y + 2;

    drawText(pixels, stride, text, text_x, text_y, text_color);
}

test "font draws glyphs and text" {
    var pixels: [100 * 50]u32 = undefined;
    @memset(&pixels, 0);

    drawText(&pixels, 100, "SAM 3", 10, 10, 0x00ffffff);

    var has_white = false;
    for (pixels) |p| {
        if (p == 0x00ffffff) {
            has_white = true;
            break;
        }
    }
    try std.testing.expect(has_white);
}

test "drawButton renders background and border" {
    var pixels: [100 * 50]u32 = undefined;
    @memset(&pixels, 0);

    drawButton(&pixels, 100, 10, 10, 80, 30, "Test", false, true, 0x0000dc64);
    try std.testing.expectEqual(@as(u32, 0x0000dc64), pixels[10 * 100 + 10]);
}
